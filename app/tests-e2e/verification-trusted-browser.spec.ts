browserTest("changing explicit connections fences the late input result in the actual UI", async ({ page, browserApp, browserTarget, request }) => {
  browserTest.skip(!process.env.RUNPHANTOM_TEST_BROWSER_MODULE, "Explicit installed closure required for real browser qualification.");
  await page.goto(`${browserApp.url}/verification`); const panel = page.getByRole("region", { name: "Trusted browser", exact: true });
  await panel.getByLabel(/^Browser target URL/).fill(browserTarget.origin);
  await panel.getByRole("button", { name: "Open browser", exact: true }).click();
  await expect(panel.getByRole("combobox", { name: "Browser connection", exact: true })).toContainText("ready");
  const first = (await (await request.get(`${browserApp.url}/api/verification/browser/sessions`)).json())[0];
  await panel.getByRole("button", { name: "Open browser", exact: true }).click();
  await expect(panel.getByRole("combobox", { name: "Browser connection", exact: true }).locator("option")).toHaveCount(3);
  const second = (await (await request.get(`${browserApp.url}/api/verification/browser/sessions`)).json()).find((session: { id: string }) => session.id !== first.id);
  await panel.getByRole("combobox", { name: "Browser connection", exact: true }).selectOption(first.id);
  await panel.getByLabel(/^Browser control target/).fill("#covered"); await panel.getByLabel("Element selector", { exact: true }).fill("#paid");
  const completion = page.waitForResponse(response => response.url().endsWith(`/browser/sessions/${first.id}/check`));
  await panel.getByRole("button", { name: "Run outcome check", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("Checking declared browser outcome");
  await panel.getByRole("combobox", { name: "Browser connection", exact: true }).selectOption(second.id);
  const completed = await completion; expect(completed.status()).toBe(200); expect((await completed.json()).report.status).toBe("inconclusive");
  await expect(panel.getByRole("combobox", { name: "Browser connection", exact: true })).toHaveValue(second.id);
  await expect(panel.getByLabel("Browser input result", { exact: true })).toHaveCount(0);
  expect(browserTarget.events.filter(event => event.type === "covered")).toEqual([]);
});
