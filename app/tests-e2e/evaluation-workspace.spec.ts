import { test, expect } from "./fixtures";
import { createEvaluationDataset, EVALUATION_RUNS, seedEvaluationRuns, startEvaluation } from "./evaluation-fixture";

test.use({ viewport: { width: 1440, height: 900 } });

test("evaluation workspace: find saved experiments without changing original outcomes", async ({ page, request, runPhantom }, testInfo) => {
  await seedEvaluationRuns(request, runPhantom.url);
  const revision = await createEvaluationDataset(request, runPhantom.url, [{ kind: "output", operation: "contains", value: "paid" }], "Checkout quality");
  const passing = await startEvaluation(request, runPhantom.url, revision, EVALUATION_RUNS.baseline, "Approved checkout");
  const failing = await startEvaluation(request, runPhantom.url, revision, EVALUATION_RUNS.rejected, "Declined checkout");
  for (let index = 1; index <= 7; index++) await startEvaluation(request, runPhantom.url, revision, EVALUATION_RUNS.repaired, `Checkout trial ${index}`);
  await page.goto(`${runPhantom.url}/evaluations?datasetId=${revision.datasetId}&version=${revision.version}`);
  const search = page.getByRole("searchbox", { name: "Search experiments", exact: true });
  const list = page.getByRole("region", { name: "Experiment list", exact: true });
  await expect(list.getByRole("button", { name: /^Open experiment / })).toHaveCount(8);
  await page.getByRole("button", { name: "Next experiments", exact: true }).click();
  await expect(list.getByRole("button", { name: /^Open experiment / })).toHaveCount(1);
  await expect(page.getByRole("button", { name: "Next experiments", exact: true })).toBeDisabled();
  await search.fill("not a real experiment");
  await expect(page.getByText("No experiments match these filters.", { exact: true })).toBeVisible();
  await expect(list).not.toBeVisible();
  await page.getByRole("button", { name: "Show all experiments", exact: true }).click();
  await expect(search).toHaveValue("");
  await expect(list.getByRole("button", { name: /^Open experiment / })).toHaveCount(8);
  await page.getByRole("combobox", { name: "Experiment outcome", exact: true }).selectOption("fail");
  await expect(list.getByRole("button", { name: /^Open experiment / })).toHaveCount(1);
  await list.getByRole("button", { name: "Open experiment Declined checkout", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "View experiment", exact: true })).toHaveValue(failing.id);
  const results = page.getByRole("region", { name: "Experiment results", exact: true });
  await expect(results.getByRole("article", { name: "Checkout result: fail", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Clear filters", exact: true }).click();
  await search.fill("APPROVED");
  await list.getByRole("button", { name: "Open experiment Approved checkout", exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("combobox", { name: "View experiment", exact: true })).toHaveValue(passing.id);
  await expect(results.getByRole("article", { name: "Checkout result: pass", exact: true })).toBeVisible();
  const stored = await request.get(`${runPhantom.url}/api/evaluations/experiments/${failing.id}`);
  expect((await stored.json()).verdict).toBe("fail");
  const review = results.getByRole("region", { name: "Human review", exact: true });
  await review.getByRole("combobox", { name: "Review case", exact: true }).selectOption(revision.cases[0].id);
  await review.getByRole("textbox", { name: "Review note", exact: true }).fill("Retain the measured output and original verdict.");
  await review.getByRole("button", { name: "Save human review", exact: true }).click();
  await expect(results.getByText(/Latest human review: Pass — Retain the measured output/)).toBeVisible();
  const appearance = await page.evaluate(async () => { await document.fonts.ready; return { accent: getComputedStyle(document.documentElement).getPropertyValue("--rp-accent").trim().toUpperCase(), heading: getComputedStyle(document.querySelector("h1")!).fontFamily, syne: document.fonts.check("28px Syne"), inter: [...document.fonts].some(font => font.family.replace(/["']/g, "") === "Inter Variable" && font.status === "loaded") }; });
  expect(appearance.accent).toBe("#0021CC");
  expect(appearance.heading).toContain("Syne");
  expect(appearance.syne && appearance.inter).toBe(true);
  await page.getByRole("heading", { name: "Evaluations", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("evaluation-workspace-desktop.png"), fullPage: true });
  for (const width of [390, 320, 768, 1024, 1280]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width);
    await expect(page.getByRole("navigation", { name: "Evaluation workspaces", exact: true }).getByRole("link", { name: "Prompt lab", exact: true })).toBeVisible();
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: testInfo.outputPath("evaluation-workspace-mobile.png"), fullPage: true });
  await list.scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("evaluation-experiments-mobile.png"), fullPage: true });
  await list.focus();
  await page.keyboard.press("ArrowRight");
  await expect.poll(() => list.evaluate(element => element.scrollLeft)).toBeGreaterThan(0);
  await page.emulateMedia({ reducedMotion: "reduce" });
  const nav = page.getByRole("navigation", { name: "Evaluation workspaces", exact: true });
  const motionSeconds = await nav.getByRole("button", { name: "External reports", exact: true }).evaluate(element => getComputedStyle(element).transitionDuration.split(",").map(value => parseFloat(value)));
  expect(motionSeconds.every(value => value <= 0.00001)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => { document.documentElement.style.zoom = "2"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await search.fill("checkout");
  await expect(search).toHaveValue("checkout");
  await page.screenshot({ path: testInfo.outputPath("evaluation-workspace-css200.png"), fullPage: true });
});

test("evaluation workspace: navigation keeps revision links and connects real curation tools", async ({ page, request, runPhantom }) => {
  await seedEvaluationRuns(request, runPhantom.url);
  const revision = await createEvaluationDataset(request, runPhantom.url, [{ kind: "json" }], "Frozen selection");
  await page.goto(`${runPhantom.url}/evaluations?datasetId=${revision.datasetId}&version=${revision.version}`);
  const nav = page.getByRole("navigation", { name: "Evaluation workspaces", exact: true });
  await nav.getByRole("button", { name: "External reports", exact: true }).click();
  await expect(page.getByRole("heading", { name: "External reports", exact: true })).toBeVisible();
  await expect(page).toHaveURL(new RegExp(`datasetId=${revision.datasetId}&version=2&view=evidence`));
  await nav.getByRole("button", { name: "Finding comparison", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Finding comparison", exact: true })).toBeVisible();
  await nav.getByRole("button", { name: "Regression workbench", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Revision", exact: true })).toHaveValue("2");
  await nav.getByRole("link", { name: "Review queues", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Review queues", exact: true })).toBeVisible();
  await expect(nav.getByRole("link", { name: "Review queues", exact: true })).toHaveAttribute("aria-current", "page");
  await page.getByRole("textbox", { name: "New queue name", exact: true }).fill("Checkout curation");
  await page.getByRole("button", { name: "Create queue", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Review queue", exact: true })).not.toHaveValue("");
  await nav.getByRole("link", { name: "Prompt lab", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Prompts", exact: true })).toBeVisible();
  await expect(nav.getByRole("link", { name: "Prompt lab", exact: true })).toHaveAttribute("aria-current", "page");
  await nav.getByRole("link", { name: "Regression workbench", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Evaluations", exact: true })).toBeVisible();
  await page.reload();
  const queues = await request.get(`${runPhantom.url}/api/review-queues`);
  expect((await queues.json()).some((value: { name: string }) => value.name === "Checkout curation")).toBe(true);
});
